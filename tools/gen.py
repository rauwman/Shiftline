"""Generates the parts of the plugin that follow from the profile script.

Reads SL_DEFAULTS and the test scenarios out of Shiftline.plugin.js and writes
Settings.cs (all simple settings, as a partial class) and TestScenarios.cs into the plugin
project folder, so plugin and script can never disagree on names, types or defaults.
Everything else in the project (plugin class, XAML pages, controls, csproj) is hand-written.

Usage: python3 -I gen.py <project_dir>      e.g.  python3 -I gen.py ../plugin/Shiftline
Also writes gen_summary.json next to this script for check.py.
"""
import json
import os
import re
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))
proj = sys.argv[1]
js_path = os.path.join(here, 'Shiftline.plugin.js')
NS = 'Shiftline.Plugin'

# ---------------------------------------------------------------- read script data
node_code = r'''
const vm = require('vm'), fs = require('fs');
const src = fs.readFileSync(process.argv[1], 'utf8');
const ctx = { $prop: () => undefined, Date, Math, Array, Object, JSON, parseInt, isFinite, Number, String, RegExp };
vm.createContext(ctx);
vm.runInContext(src + '\nthis.D = SL_DEFAULTS; this.S = SL_TEST_SCENARIOS.map(s => s[0]); this.MS = SL_MAX_SIDE; this.MC = SL_MAX_CENTRE; this.LD = SL_LAYER_DEFS.map(d => [d.id, d.label]); this.FP = Object.fromEntries(Object.keys(SL_FX_POSITIONS).map(k => [k, [1,2,3,4,5,6,7,8].map(S => SL_FX_POSITIONS[k](S))]));', ctx);
console.log(JSON.stringify({ defaults: ctx.D, scenarios: ctx.S, maxSide: ctx.MS, maxCentre: ctx.MC, layers: ctx.LD, positions: ctx.FP }));
'''
data = json.loads(subprocess.check_output(['node', '-e', node_code, js_path], text=True))
defaults, scenarios = data['defaults'], data['scenarios']
MAX_SIDE, MAX_CENTRE = data['maxSide'], data['maxCentre']
LAYERS = data['layers']
POSITIONS = data['positions']
import hashlib
SCRIPT_BUILD = hashlib.sha1(open(js_path, encoding='utf-8').read().replace('\r\n', '\n').encode('utf-8')).hexdigest()[:8]
HEX = re.compile(r'^#[0-9A-Fa-f]{6}$')

def kind_of(value):
    if isinstance(value, bool):
        return 'bool'
    if isinstance(value, int):
        return 'int'
    if isinstance(value, str) and HEX.match(value):
        return 'colour'
    return 'string'



# ---------------------------------------------------------------- Settings.cs
def pascal_field(name):
    return '_' + name[0].lower() + name[1:]

def cs_literal(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'

def cs_type(value):
    return {'bool': 'bool', 'int': 'int'}.get(kind_of(value), 'string')

lines = []
lines.append('// <auto-generated>')
lines.append('// Generated by gen.py from SL_DEFAULTS in Shiftline.plugin.js. Do not edit by hand.')
lines.append('// </auto-generated>')
lines.append('using System.Collections.Generic;')
lines.append('using System.ComponentModel;')
lines.append('using System.Text.RegularExpressions;')
lines.append('')
lines.append('namespace %s' % NS)
lines.append('{')
lines.append('    /// <summary>')
lines.append('    /// All simple settings of the plugin (text, number, switch). Public properties are saved as JSON by SimHub and')
lines.append('    /// published as Shiftline.&lt;PropertyName&gt; for the LED profile script. The colour themes live in Settings.Themes.cs.')
lines.append('    /// </summary>')
lines.append('    public partial class Settings : INotifyPropertyChanged')
lines.append('    {')
lines.append('        private static readonly Regex HexColour = new Regex("^#[0-9A-Fa-f]{6}$");')
lines.append('')
lines.append('        /// <summary>The settings the LED script reads; the plugin publishes exactly these as Shiftline.&lt;Name&gt;.</summary>')
lines.append('        /// <summary>Identifies the LED profile script this plugin was generated with; the matching profile is named Shiftline [this].</summary>')
lines.append('        public const string ScriptBuild = "%s";' % SCRIPT_BUILD)
lines.append('')
lines.append('        /// <summary>The effect layers in the standard order, lowest priority first: id used in LayerOrder and name shown to the user.</summary>')
lines.append('        public static readonly string[][] LayerDefs =')
lines.append('        {')
for i, (lid, label) in enumerate(LAYERS):
    lines.append('            new[] { "%s", "%s" }%s' % (lid, label, ',' if i < len(LAYERS) - 1 else ''))
lines.append('        };')
lines.append('')
lines.append('        /// <summary>Standard position of every side effect for 1 to 8 LEDs per side: { start (1 = outermost), count }.</summary>')
lines.append('        public static readonly Dictionary<string, int[][]> EffectPositions = new Dictionary<string, int[][]>')
lines.append('        {')
for name, per_side in POSITIONS.items():
    lines.append('            { "%s", new[] { %s } },' % (name, ', '.join('new[] { %d, %d }' % (a, b) for a, b in per_side)))
lines.append('        };')
lines.append('')
lines.append('        public static readonly string[] ScriptSettingNames =')
lines.append('        {')
for i, name in enumerate(defaults):
    lines.append('            "%s"%s' % (name, ',' if i < len(defaults) - 1 else ''))
lines.append('        };')
lines.append('')
lines.append('        public event PropertyChangedEventHandler PropertyChanged;')
lines.append('')
lines.append('        private void Raise(string propertyName)')
lines.append('        {')
lines.append('            PropertyChangedEventHandler handler = PropertyChanged;')
lines.append('            if (handler != null)')
lines.append('            {')
lines.append('                handler(this, new PropertyChangedEventArgs(propertyName));')
lines.append('            }')
lines.append('        }')
for name, value in defaults.items():
    t, k, f = cs_type(value), kind_of(value), pascal_field(name)
    lines.append('')
    lines.append('        private %s %s = %s;' % (t, f, cs_literal(value)))
    lines.append('        public %s %s' % (t, name))
    lines.append('        {')
    lines.append('            get { return %s; }' % f)
    lines.append('            set')
    lines.append('            {')
    if k == 'colour':
        lines.append('                // Ignore text that is not a #RRGGBB colour (typing in progress); the last valid colour stays.')
        lines.append('                if (value == null || !HexColour.IsMatch(value))')
        lines.append('                {')
        lines.append('                    return;')
        lines.append('                }')
        lines.append('')
        lines.append('                value = value.ToUpperInvariant();')
    elif t == 'string':
        lines.append('                if (value == null)')
        lines.append('                {')
        lines.append('                    return;')
        lines.append('                }')
        lines.append('')
    lines.append('                if (%s != value)' % f)
    lines.append('                {')
    lines.append('                    %s = value;' % f)
    lines.append('                    Raise("%s");' % name)
    lines.append('                }')
    lines.append('            }')
    lines.append('        }')
lines.append('')
lines.append('        /// <summary>Restores every simple setting to its default (colour themes: see ResetAll).</summary>')
lines.append('        public void ResetToDefaults()')
lines.append('        {')
for name, value in defaults.items():
    lines.append('            %s = %s;' % (name, cs_literal(value)))
lines.append('        }')
lines.append('')
lines.append('        /// <summary>Restores one setting to its default; false when the name is not a setting.</summary>')
lines.append('        public bool ResetSetting(string name)')
lines.append('        {')
lines.append('            switch (name)')
lines.append('            {')
for name, value in defaults.items():
    lines.append('                case "%s":' % name)
    lines.append('                    %s = %s;' % (name, cs_literal(value)))
    lines.append('                    return true;')
lines.append('                default:')
lines.append('                    return false;')
lines.append('            }')
lines.append('        }')
lines.append('    }')
lines.append('}')
settings_cs = '\n'.join(lines) + '\n'

# ---------------------------------------------------------------- TestScenarios.cs
sc = ['// <auto-generated>',
      '// Generated by gen.py from SL_TEST_SCENARIOS in Shiftline.plugin.js. Do not edit by hand.',
      '// The index of a name is the value of the TestScenario setting.',
      '// </auto-generated>',
      'namespace %s' % NS, '{',
      '    public static class TestScenarios', '    {',
      '        public static readonly string[] Names =', '        {']
for i, name in enumerate(scenarios):
    sc.append('            %s%s' % (cs_literal(name), ',' if i < len(scenarios) - 1 else ''))
sc += ['        };', '    }', '}']
scenarios_cs = '\n'.join(sc) + '\n'


# ---------------------------------------------------------------- TabSettings.cs
# The settings every tab of the LED page shows (every binding inside the tab), for "Reset this tab".
# The layout and the LED function sit above the tabs and are never part of a tab reset.
NOT_RESET = {'LedFunction', 'SideLeds', 'CentreLeds'}
xaml = open(os.path.join(proj, 'LedPage.xaml'), encoding='utf-8-sig').read()
heads = [(m.start(), m.group(1)) for m in re.finditer(r'<TabItem Header="([^"]+)"', xaml)]
tab_settings = {}
for (start, header), end in zip(heads, [h[0] for h in heads[1:]] + [len(xaml)]):
    seg = xaml[start:end]
    found = set(re.findall(r'\{Binding (\w+)', seg)) | set(re.findall(r'<Binding Path="(\w+)"', seg))
    tab_settings[header] = sorted((found & set(defaults)) - NOT_RESET)
ts = ['// <auto-generated>',
      '// Generated by gen.py from the bindings of every tab in LedPage.xaml. Do not edit by hand.',
      '// </auto-generated>',
      'using System.Collections.Generic;', '',
      'namespace %s' % NS, '{',
      '    public static class TabSettings', '    {',
      '        /// <summary>The settings shown on each tab of the LED page, by the tab header.</summary>',
      '        public static readonly Dictionary<string, string[]> ByTab = new Dictionary<string, string[]>',
      '        {']
for header, names in tab_settings.items():
    ts.append('            { %s, new[] { %s } },' % (cs_literal(header), ', '.join(cs_literal(n) for n in names)))
ts += ['        };', '    }', '}']
tabsettings_cs = '\n'.join(ts) + '\n'


# ---------------------------------------------------------------- write
def write(name, text):
    with open(os.path.join(proj, name), 'w', encoding='utf-8-sig', newline='\r\n') as f:
        f.write(text)

write('Settings.cs', settings_cs)
write('TestScenarios.cs', scenarios_cs)
write('TabSettings.cs', tabsettings_cs)
json.dump({'defaults': defaults, 'scenarios': scenarios, 'maxSide': MAX_SIDE, 'maxCentre': MAX_CENTRE},
          open(os.path.join(here, 'gen_summary.json'), 'w'), indent=1)
print('generated', len(defaults), 'settings,', len(scenarios), 'scenarios ->', proj)
